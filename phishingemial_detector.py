# SECTION 8 — IMPROVEMENT 2: ENSEMBLE STACKING (SVM + RoBERTa)
# WHY: Fuses lexical strength of TF-IDF+SVM with semantic strength of RoBERTa
# Aljabri & Alharbi (2025): ensembles outperform single models by avg 4.7%
print("SECTION 8 — IMPROVEMENT 2: ENSEMBLE STACKING")
def get_roberta_probs(loader,mdl,dev):
    mdl.eval(); all_probs=[]
    with torch.no_grad():
        for batch in loader:
            out   = mdl(input_ids=batch["input_ids"].to(dev),
                        attention_mask=batch["attention_mask"].to(dev))
            probs = torch.softmax(out.logits,dim=1).cpu().numpy()
            all_probs.append(probs)
    return np.vstack(all_probs)

# Cap cv folds to min class count — prevents StratifiedKFold error on small datasets
min_class = min(Counter(y_train).values())
cv_folds  = min(3,min_class)
print(f"  Calibrating SVM (cv={cv_folds})...")
svm_cal = CalibratedClassifierCV(LinearSVC(C=1.0,class_weight="balanced",random_state=42),
                                  cv=cv_folds,method="isotonic")
svm_cal.fit(X_train_tfidf,y_train)

print("  Extracting probability vectors...")
train_svm_probs     = svm_cal.predict_proba(X_train_tfidf)
test_svm_probs      = svm_cal.predict_proba(X_test_tfidf)
train_roberta_probs = get_roberta_probs(train_dl,model,DEVICE)
test_roberta_probs  = get_roberta_probs(test_dl,model,DEVICE)

# Meta-features: [SVM_p(ham), SVM_p(spam), SVM_p(phish),
#                 Rob_p(ham), Rob_p(spam), Rob_p(phish)]
X_meta_train = np.hstack([train_svm_probs,train_roberta_probs])
X_meta_test  = np.hstack([test_svm_probs, test_roberta_probs])
print(f"  Meta-feature matrix: {X_meta_train.shape}")

print("  Training Logistic Regression meta-learner...")
meta_clf       = LogisticRegression(C=10.0,max_iter=1000,random_state=42)
meta_clf.fit(X_meta_train,y_train)
ensemble_preds = meta_clf.predict(X_meta_test)

ensemble_acc = accuracy_score(y_test,ensemble_preds)
ensemble_f1  = f1_score(y_test,ensemble_preds,average="macro",zero_division=0)
per_rec       = recall_score(y_test,ensemble_preds,average=None,zero_division=0)
ensemble_fnr  = 1-per_rec[2] if len(per_rec)>2 else 0.0
print(f"\n  ✅ Ensemble — Acc={ensemble_acc:.4f}  F1={ensemble_f1:.4f}  Phish-FNR={ensemble_fnr:.4f}")
print(classification_report(y_test,ensemble_preds,target_names=LABEL_NAMES,zero_division=0))

# SECTION 9 — IMPROVEMENT 3: SHAP EXPLAINABILITY
# WHY: Identifies which words drive each prediction — fills interpretability gap
# Lundberg & Lee (2017); Mahboob et al. (2025)
#
