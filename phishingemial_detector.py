def predict_email(text: str) -> dict:
    """
    Predict a single email using ensemble voting of NB + LR + SVM.
    Returns label, confidence %, per-class breakdown, and signal analysis.
    """
    cleaned  = clean_text(text)
    features = tfidf.transform([cleaned])
    nb_p  = nb_model.predict_proba(features)[0]
    lr_p  = lr_model.predict_proba(features)[0]
    svm_p = svm_cal.predict_proba(features)[0]
    avg   = (nb_p + lr_p + svm_p) / 3.0
    idx   = int(np.argmax(avg))

    url_cnt   = len(re.findall(r"http[s]?://\S+", str(text)))
    exclam    = text.count("!")
    urg_words = [w for w in URGENCY_WORDS if w in text.lower()]
    caps_r    = sum(1 for c in text if c.isupper()) / max(len([c for c in text if c.isalpha()]),1)

    return {
        "label"        : LABEL_NAMES[idx],
        "confidence"   : float(avg[idx]) * 100,
        "ham_pct"      : float(avg[0]) * 100,
        "spam_pct"     : float(avg[1]) * 100,
        "phishing_pct" : float(avg[2]) * 100,
        "url_count"    : url_cnt,
        "exclamations" : exclam,
        "urgency_words": urg_words,
        "caps_ratio"   : round(caps_r * 100, 1),
    }

def print_email_result(email_text: str, true_label: str = None):
    """Pretty-print a single email prediction with full breakdown."""
    r     = predict_email(email_text)
    label = r["label"]
    icons = {"ham": "✅", "spam": "⚠️ ", "phishing": "🚨"}
    sep   = "─" * 62

    print(f"\n  {sep}")
    preview = email_text[:70] + ("..." if len(email_text) > 70 else "")
    print(f"  📧  {preview}")
    print(f"  {icons[label]}  PREDICTION : {label.upper()}   ({r['confidence']:.1f}% confidence)")
    if true_label:
        is_correct = label == true_label
        mark = "✅ CORRECT" if is_correct else f"❌ WRONG (true={true_label.upper()})"
        print(f"       True label  : {true_label.upper()}  →  {mark}")
    print(f"\n       Probabilities:")
    for cls, pct in [("ham", r["ham_pct"]), ("spam", r["spam_pct"]), ("phishing", r["phishing_pct"])]:
        bar = "█" * int(pct / 5)
        print(f"         {cls:<10} {bar:<20} {pct:>5.1f}%")
    print(f"\n       Signal analysis:")
    print(f"         URLs found       : {r['url_count']}")
    print(f"         Exclamation marks: {r['exclamations']}")
    print(f"         Caps ratio       : {r['caps_ratio']}%")
    words = r["urgency_words"]
    print(f"         Urgency words    : {', '.join(words[:5]) if words else 'none detected'}")

