def clean_text(text: str) -> str:
    # 1 strip HTML
    text = BeautifulSoup(str(text), "lxml").get_text(separator=" ")
    # 2 remove email headers
    for p in [r"From:.*?\n",r"To:.*?\n",r"Subject:.*?\n",r"-----Original Message-----.*"]:
        text = re.sub(p," ",text,flags=re.IGNORECASE|re.DOTALL)
    # 3 replace email addresses
    text = re.sub(r"[\w\.\-]+@[\w\.\-]+\.\w+"," EMAILTOKEN ",text)
    # 4 replace money amounts
    text = re.sub(r"[£$€]\s?\d[\d,\.]*"," MONEYTOKEN ",text)
    # 5 replace URLs — keep URLTOKEN as a phishing signal
    text = re.sub(r"http[s]?://\S+"," URLTOKEN ",text)
    # 6 lowercase
    text = text.lower()
    # 7 remove punctuation / special chars
    text = re.sub(r"[^a-z0-9\s]"," ",text)
    text = re.sub(r"\b\d{5,}\b"," ",text)
    text = re.sub(r"\s+"," ",text).strip()
    # 8 lemmatise — keep placeholder tokens even if they match stopwords
    tokens = [lemmatizer.lemmatize(t) for t in text.split()
              if t not in STOPWORDS or "token" in t]
    return " ".join(tokens)

