# SECTION 7 — IMPROVEMENT 1: RoBERTa FINE-TUNING
# WHY RoBERTa: removes NSP task, 10x more training data, dynamic masking
# → +1.5-3% F1 over BERT (Melendez et al. 2024, Jamal et al. 2024)
print("SECTION 7 — IMPROVEMENT 1: RoBERTa FINE-TUNING")
MODEL_NAME   = "roberta-base"
MAX_LEN      = 256    # balances accuracy vs GPU memory
BATCH_SIZE   = 16     # reduce to 8 if CUDA out-of-memory error appears
EPOCHS       = 4
LR           = 2e-5
WARMUP_RATIO = 0.1
NUM_LABELS   = 3

class EmailDataset(Dataset):
    def __init__(self,texts,labels,tokenizer,max_len):
        self.texts=list(texts); self.labels=list(labels)
        self.tokenizer=tokenizer; self.max_len=max_len
    def __len__(self): return len(self.texts)
    def __getitem__(self,idx):
        enc = self.tokenizer(self.texts[idx],max_length=self.max_len,
                             padding="max_length",truncation=True,return_tensors="pt")
        return {"input_ids"     : enc["input_ids"].squeeze(0),
                "attention_mask": enc["attention_mask"].squeeze(0),
                "label"         : torch.tensor(self.labels[idx],dtype=torch.long)}

print(f"Loading {MODEL_NAME}...")
tokenizer = RobertaTokenizer.from_pretrained(MODEL_NAME)
model     = RobertaForSequenceClassification.from_pretrained(
    MODEL_NAME,num_labels=NUM_LABELS,
    hidden_dropout_prob=0.1,attention_probs_dropout_prob=0.1).to(DEVICE)
print(f"Parameters: {sum(p.numel() for p in model.parameters()):,}")

train_ds = EmailDataset(X_train.tolist(),y_train,tokenizer,MAX_LEN)
val_ds   = EmailDataset(X_val.tolist(),  y_val,  tokenizer,MAX_LEN)
test_ds  = EmailDataset(X_test.tolist(), y_test, tokenizer,MAX_LEN)
train_dl = DataLoader(train_ds,batch_size=BATCH_SIZE,shuffle=True, num_workers=2,pin_memory=True)
val_dl   = DataLoader(val_ds,  batch_size=BATCH_SIZE,shuffle=False,num_workers=2,pin_memory=True)
test_dl  = DataLoader(test_ds, batch_size=BATCH_SIZE,shuffle=False,num_workers=2,pin_memory=True)

optimizer   = AdamW(model.parameters(),lr=LR,eps=1e-8,weight_decay=0.01)
total_steps = len(train_dl)*EPOCHS
scheduler   = get_linear_schedule_with_warmup(optimizer,
                  num_warmup_steps=int(total_steps*WARMUP_RATIO),
                  num_training_steps=total_steps)

# Class-weighted loss: upweights phishing (label 2) × 2.5 to reduce false-negatives
class_weights = torch.tensor([1.0,1.5,2.5]).to(DEVICE)
loss_fn = nn.CrossEntropyLoss(weight=class_weights)

training_history = []; best_val_f1 = 0.0

for epoch in range(EPOCHS):
    print(f"  Epoch {epoch+1}/{EPOCHS}")
    model.train(); total_loss = 0.0
    for batch in train_dl:
        optimizer.zero_grad()
        out  = model(input_ids=batch["input_ids"].to(DEVICE),
                     attention_mask=batch["attention_mask"].to(DEVICE))
        loss = loss_fn(out.logits,batch["label"].to(DEVICE))
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(),1.0)
        optimizer.step(); scheduler.step()
        total_loss += loss.item()
    avg_loss = total_loss/len(train_dl)

    model.eval(); val_preds,val_true = [],[]
    with torch.no_grad():
        for batch in val_dl:
            out = model(input_ids=batch["input_ids"].to(DEVICE),
                        attention_mask=batch["attention_mask"].to(DEVICE))
            val_preds.extend(torch.argmax(out.logits,dim=1).cpu().numpy())
            val_true.extend(batch["label"].numpy())
    val_f1  = f1_score(val_true,val_preds,average="macro",zero_division=0)
    val_acc = accuracy_score(val_true,val_preds)
    print(f"  Train Loss={avg_loss:.4f}  Val Acc={val_acc:.4f}  Val F1={val_f1:.4f}")
    training_history.append({"epoch":epoch+1,"train_loss":avg_loss,
                              "val_acc":val_acc,"val_f1":val_f1})
    if val_f1 > best_val_f1:
        best_val_f1 = val_f1
